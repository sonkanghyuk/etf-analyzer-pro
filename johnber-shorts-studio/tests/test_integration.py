    def test_05_silence_speed_video_audio_subtitle_event_sync(self):
        silence = media.silence_ranges(self.source,0,10,threshold=-35,min_duration=.5,padding=0)
        self.assertEqual(len(silence),1)
        self.assertAlmostEqual(silence[0]['start'],4,delta=.03)
        self.assertAlmostEqual(silence[0]['end'],6,delta=.03)
        expected = [.8,2.4,4.,5.6]
        raw = run(['ffmpeg','-v','error','-threads','2','-i',str(self.sample),'-map','0:a:0','-ac','1','-ar','48000','-f','s16le','-']).stdout
        audio = array('h'); audio.frombytes(raw)
        window=480
        audio_flags = [(sum(v*v for v in audio[i:i+window])/max(1,len(audio[i:i+window])))**.5 > 6000 for i in range(0,len(audio),window)]
        audio_events = event_starts(audio_flags,.01)
        raw = run(['ffmpeg','-v','error','-threads','2','-i',str(self.sample),'-vf','crop=60:30:510:830,scale=8:4,format=gray','-f','rawvideo','-threads','2','-']).stdout
        video_events = event_starts([sum(raw[i:i+32])/32>180 for i in range(0,len(raw),32)],1/30)
        raw = run(['ffmpeg','-v','error','-threads','2','-i',str(self.sample),'-vf','crop=960:430:60:1270,scale=120:54,format=gray','-f','rawvideo','-threads','2','-']).stdout
        chunk=120*54
        cue_events = event_starts([sum(v>100 for v in raw[i:i+chunk])>12 for i in range(0,len(raw),chunk)],1/30)
        cue_events = [v for v in cue_events if v>.7]
        for events in (audio_events,video_events,cue_events):
            self.assertEqual(len(events),4,(events,expected))
            for actual, want in zip(events,expected): self.assertLessEqual(abs(actual-want),.1,(events,expected))
        self.metrics['sync'] = dict(expected_seconds=expected,audio_onsets=audio_events,video_onsets=video_events,subtitle_onsets=cue_events,detected_silence=silence,audio_duration=len(audio)/48000,caption_rounding='ceil to 1/30 seconds',inspection='Decoded pulse RMS/frame luminance; no human listening or ASR timing claim')

    def test_06_shared_preview_matches_render_text_at_multiple_times(self):
        comparisons=[]
        for second in (0,.4,2.5,4.1,6.1):
            response = self.request('GET',f'/api/projects/{self.project["id"]}/frame',params={'clip_id':self.clip['id'],'time':second})
            preview = Image.open(BytesIO(response.content)).convert('RGB')
            final = decode_frame(self.sample,second)
            preview.save(OUTPUT/f'preview-{second:.1f}.png')
            final.save(OUTPUT/f'render-{second:.1f}.png')
            errors=[]
            for box in ((0,0,1080,500),(0,1200,1080,1920)):
                a,b=preview.crop(box),final.crop(box)
                difference=ImageChops.difference(a,b)
                errors.append(sum(ImageStat.Stat(difference).mean)/3)
                self.assertLess(errors[-1],4.0,(second,errors))
                # Thresholded text boundaries independently check layout: codec
                # color noise is ignored; a shifted/wrapped glyph changes bbox.
                ma=a.convert('L').point(lambda v:255 if v>110 else 0)
                mb=b.convert('L').point(lambda v:255 if v>110 else 0)
                ba,bb=ma.getbbox(),mb.getbbox()
                if ba or bb:
                    self.assertIsNotNone(ba); self.assertIsNotNone(bb)
                    self.assertTrue(all(abs(x-y)<=5 for x,y in zip(ba,bb)),(second,ba,bb))
            comparisons.append(dict(time=second,mean_rgb_error=errors))
        self.metrics['preview_comparison']=comparisons

