    def wait(self, identifier):
        deadline = time.monotonic() + 120
        while time.monotonic() < deadline:
            obj = self.request('GET',f'/api/jobs/{identifier}').json()
            if obj['state'] not in jobs.ACTIVE:
                return obj
            time.sleep(.15)
        self.fail('Actual processing did not reach terminal state in 120 seconds')

