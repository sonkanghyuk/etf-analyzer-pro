def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def decode_frame(path, second):
    frame = int(second * 30 + 1e-6)
    raw = run(['ffmpeg', '-v', 'error', '-threads', '2', '-i', str(path), '-vf', f'select=eq(n\\,{frame})', '-frames:v', '1', '-threads', '2', '-f', 'image2pipe', '-vcodec', 'png', '-']).stdout
    return Image.open(BytesIO(raw)).convert('RGB')


def event_starts(flags, step):
    return [round(i * step, 6) for i, active in enumerate(flags) if active and (i == 0 or not flags[i - 1])]


